"""法令の正式名称と、検索時に許容する既知略称。"""

from __future__ import annotations


LAW_TITLE_ALIASES: dict[str, tuple[str, ...]] = {
    "金融商品取引法": ("金商法",),
    "金融商品取引法施行令": ("金商法施行令",),
    "企業内容等の開示に関する内閣府令": ("開示府令",),
    "発行者以外の者による株券等の公開買付けの開示に関する内閣府令": (
        "公開買付府令",
    ),
    "金融商品取引法第二条に規定する定義に関する内閣府令": ("定義府令",),
    "医薬品、医療機器等の品質、有効性及び安全性の確保等に関する法律": (
        "薬機法",
    ),
    "医薬品、医療機器等の品質、有効性及び安全性の確保等に関する法律施行規則": (
        "薬機法施行規則",
    ),
}


def law_title_names(title: str) -> tuple[str, ...]:
    """正式名称を先頭に、既知略称を重複なく返す。"""
    return tuple(dict.fromkeys((title, *LAW_TITLE_ALIASES.get(title, ()))))
